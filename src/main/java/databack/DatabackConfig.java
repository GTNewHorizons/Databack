package databack;

import com.gtnewhorizon.gtnhlib.config.Config;

@Config(modid = Databack.MODID)
public class DatabackConfig {

    @Config.Comment("Dump .class files generated by the density function bytecode compiler. Useful for inspecting generated bytecode.")
    @Config.DefaultBoolean(false)
    public static boolean dumpCompiledDensityFunctions;

    @Config.Comment("Directory to write compiled density function .class files into. Relative to the Minecraft run directory.")
    @Config.DefaultString("compiled-df")
    public static String compiledDensityFunctionDumpDir;

    @Config.Comment({ "Use a new biome for every datapack biome, including modern vanilla ones, instead of reusing 1.7's",
        "vanilla biomes where modern has an equivalent. Needs many biome ids; with EndlessIDs that is not a problem.",
        "Requires a restart." })
    @Config.DefaultBoolean(false)
    public static boolean modernBiomesOnly;

    @Config.Comment({ "Skip other mods' world generators (IWorldGenerator) in Databack worlds, so every generated block",
        "comes from Databack. Meant for development." })
    @Config.DefaultBoolean(false)
    public static boolean disableModWorldGeneration;

    @Config.Comment({ "The most chunks decorated with features per world per tick. Chunks are decorated once their",
        "neighbours exist; past this limit they wait for later ticks, which spreads the work of fast exploration." })
    @Config.DefaultInt(2)
    @Config.RangeInt(min = 1, max = 64)
    public static int decorationsPerTick;

    @Config.Comment("Enable block/item/biome/entity tag debug mode")
    @Config.DefaultBoolean(true)
    public static boolean enableTagDebugMode;

}
